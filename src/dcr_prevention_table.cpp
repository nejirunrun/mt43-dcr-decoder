static const int kPreventionCount = sizeof(kPreventions) / sizeof(kPreventions[0]);

// 留意事項コード → 文言。
//   @return 既知コードなら文言。**未知コードは nullptr**。
//
//   ★"?" のような固定文字列を返さないのは、未知コードのときに呼び出し側が
//     「留意事項コード=307」のように**数値を出せる余地を残す**ため。仕様改版で
//     新コードが増えたときに "?" へ潰すと、利用者からは情報が消えたように見える。
//     一次資料も『JMA システム改修により未定義コードが送られる場合がある』と
//     明記しており、未知コードは異常ではなく想定内。
const char* dcr_prevention_name(uint16_t code) {
    for (int i = 0; i < kPreventionCount; i++)
        if (kPreventions[i].code == code) return kPreventions[i].text;
    return nullptr;
}
